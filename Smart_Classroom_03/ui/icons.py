def svg(name, color, stroke=2.0, fill="none"):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="{fill}" stroke="{color}" '
            f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{PATHS[name]}</svg>')


def pixmap(name, color="#0F172A", size=18, stroke=2.0, fill="none", dpr=2.0):
    renderer = QSvgRenderer(QByteArray(svg(name, color, stroke, fill).encode()))
    pm = QPixmap(int(size * dpr), int(size * dpr))
    pm.fill(Qt.transparent)
    painter = QPainter(pm)
    painter.setRenderHint(QPainter.Antialiasing)
    renderer.render(painter, QRectF(0, 0, size * dpr, size * dpr))
    painter.end()
    pm.setDevicePixelRatio(dpr)
    return pm


def icon(name, color="#0F172A", size=18, stroke=2.0):
    return QIcon(pixmap(name, color, size, stroke))


def paint_icon(painter, name, rect, color, stroke=2.0):
    """Vẽ icon trực tiếp lên QPainter trong vùng rect (QRectF)."""
    QSvgRenderer(QByteArray(svg(name, color, stroke).encode())).render(painter, rect)
